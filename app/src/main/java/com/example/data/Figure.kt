        fun fromId(id: String): HistoricalFigure {
            return entries.firstOrNull { it.id.equals(id, ignoreCase = true) } ?: SOCRATES
        }

        fun getByCategory(category: String): List<HistoricalFigure> {
            if (category == "الكل" || category.isBlank()) return entries
            return entries.filter { it.categoryAr == category }
        }

        fun randomReaction(figure: HistoricalFigure, isCorrect: Boolean, isTimeout: Boolean = false): String {
            return when {
                isTimeout -> figure.reactionsTimeout.randomOrNull() ?: "الوقت خلص!"
                isCorrect -> figure.reactionsCorrect.randomOrNull() ?: "برافو عليك!"
                else -> figure.reactionsWrong.randomOrNull() ?: "للأسف غلط!"
            }
        }
    }
